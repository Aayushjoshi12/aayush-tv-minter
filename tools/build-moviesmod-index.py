#!/usr/bin/env python3
"""Build api/moviesmod-index.js from the MoviesMod sitemaps.

Downloads the 22 post sitemaps of moviesmod.tw, extracts the movie
page slugs, and writes them as a static JS module that the resolver
imports (so Vercel bundles it; the Azure transform converts the
import to require()).

Also writes data-moviesmod-index.json (the raw slug list) for reference.

Usage: python3 tools/build-moviesmod-index.py
"""
import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/126.0 Safari/537.36"
    )
}


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    return urllib.request.urlopen(req, timeout=30).read().decode("utf-8", "ignore")


def main():
    idx = fetch("https://moviesmod.tw/wp-sitemap.xml")
    sitemaps = re.findall(
        r"<loc>(https://moviesmod\.tw/post-sitemap\d*\.xml)</loc>", idx
    )
    print(f"sitemaps: {len(sitemaps)}")
    urls = []
    for sm in sitemaps:
        xml = fetch(sm)
        found = re.findall(
            r"<loc>(https://moviesmod\.tw/download-[^<]+)</loc>", xml
        )
        urls.extend(found)
        print(f"  {sm.split('/')[-1]}: {len(found)}")
    slugs = sorted({u.replace("https://moviesmod.tw/", "") for u in urls})
    # Compact: strip the common "download-" prefix and trailing "/".
    compact = [
        s[len("download-"):-1]
        if s.startswith("download-") and s.endswith("/")
        else s
        for s in slugs
    ]
    print(f"TOTAL unique movie slugs: {len(compact)}")

    # Raw JSON (reference + Azure fs fallback).
    (ROOT / "data-moviesmod-index.json").write_text(
        json.dumps(compact, separators=(",", ":"))
    )
    # Static JS module (the resolver imports this).
    header = (
        "// moviesmod-index.js — MoviesMod movie-page slugs, built from\n"
        "// the 22 post sitemaps of moviesmod.tw (21,704 entries).\n"
        "// Generated by tools/build-moviesmod-index.py; do not hand-edit.\n"
        "// The resolver imports this statically so Vercel bundles it;\n"
        "// the Azure transform converts the import to require().\n"
        "export const MOVIESMOD_SLUGS = `\n"
    )
    footer = '\n`.split("\\n").filter(Boolean);\n'
    (ROOT / "api" / "moviesmod-index.js").write_text(
        header + "\n".join(compact) + footer
    )
    print(f"wrote api/moviesmod-index.js ({(ROOT / 'api' / 'moviesmod-index.js').stat().st_size} bytes)")


if __name__ == "__main__":
    main()
